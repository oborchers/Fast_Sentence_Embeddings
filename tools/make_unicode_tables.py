"""Generate the simple lowercase table of fse_words@1 from the Unicode Character Database.

The table is part of the tokenizer contract (docs/architecture/tokenizers.md, "Tokenizers"): its Unicode
version is fixed, and changing it needs a new tokenizer identifier. The script reads
``UnicodeData.txt`` of that version (pinned by its sha256) and writes two files, which are
checked in and never edited by hand:

- ``src/fse/_unicode.py``: the table for the Python reference;
- ``src/fse/_native_src/tables/_native_unicode.h``: the same table for the native tokenizer, in two stages.

Download the file from https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt, then::

    uv run python tools/make_unicode_tables.py --ucd UnicodeData.txt
    uv run python tools/make_unicode_tables.py --ucd UnicodeData.txt --check

On a Python whose ``unicodedata`` has the same version, the script also checks every
mapping against ``str.lower`` of the single code point.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path

UNICODE_VERSION = "15.1.0"
UCD_SHA256 = "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86"
ROOT = Path(__file__).resolve().parent.parent
PYTHON_OUT = ROOT / "src" / "fse" / "_unicode.py"
HEADER_OUT = ROOT / "src" / "fse" / "_native_src" / "tables" / "_native_unicode.h"
BLOCK = 128
HEADER_NOTE = (
    f"Generated by tools/make_unicode_tables.py from UnicodeData.txt of Unicode "
    f"{UNICODE_VERSION}; do not edit. Unicode data: Copyright (c) 1991-2023 Unicode, Inc., "
    "under the Unicode License v3 (see NOTICE)."
)


def read_simple_lowercase(path: Path) -> dict[int, int]:
    """Field 13 of every entry of UnicodeData.txt that has one."""
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != UCD_SHA256:
        raise SystemExit(f"{path} has sha256 {digest}, not that of Unicode {UNICODE_VERSION}")
    table = {}
    for line in data.decode("ascii").splitlines():
        fields = line.split(";")
        if len(fields) != 15:
            raise SystemExit(f"malformed line: {line!r}")
        if fields[13]:
            table[int(fields[0], 16)] = int(fields[13], 16)
    return table


def check_against_python(table: dict[int, int]) -> None:
    """Every mapping equals str.lower of the code point, except where it gives two."""
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(f"skipped the check: Python has Unicode {unicodedata.unidata_version}")
        return
    for cp in range(sys.maxunicode + 1):
        lower = chr(cp).lower()
        want = table.get(cp, cp)
        if len(lower) == 1:
            if ord(lower) != want:
                raise SystemExit(
                    f"U+{cp:04X}: str.lower gives U+{ord(lower):04X}, field 13 U+{want:04X}"
                )
        elif cp != 0x0130:  # the only unconditional SpecialCasing lowercase
            raise SystemExit(f"U+{cp:04X}: str.lower gives {len(lower)} code points")


def python_source(table: dict[int, int]) -> str:
    pairs = [f"{cp:x}:{lower:x}" for cp, lower in sorted(table.items())]
    lines, line = [], ""
    for pair in pairs:
        if len(line) + len(pair) + 1 > 84:
            lines.append(line)
            line = ""
        line += pair + " "
    lines.append(line)
    body = "\n".join(f'    "{chunk}"' for chunk in lines)
    return f'''"""The simple lowercase mapping of fse_words@1.

{HEADER_NOTE}
"""

UNICODE_VERSION = "{UNICODE_VERSION}"

# Pairs "code point:lowercase" in hex, separated by spaces.
_PAIRS = (
{body}
)

SIMPLE_LOWERCASE: dict[int, int] = {{
    int(cp, 16): int(lower, 16) for cp, lower in (pair.split(":") for pair in _PAIRS.split())
}}
'''


def header_source(table: dict[int, int]) -> str:
    limit = (max(table) // BLOCK + 1) * BLOCK
    blocks: list[tuple[int, ...]] = []
    index: dict[tuple[int, ...], int] = {}
    stage1 = []
    for start in range(0, limit, BLOCK):
        block = tuple(table.get(cp, cp) - cp for cp in range(start, start + BLOCK))
        if block not in index:
            index[block] = len(blocks)
            blocks.append(block)
        stage1.append(index[block])
    if len(blocks) > 256:
        raise SystemExit("more than 256 distinct blocks do not fit uint8 indices")

    def rows(values, per_line):
        return ",\n".join(
            "    " + ", ".join(str(v) for v in values[i : i + per_line])
            for i in range(0, len(values), per_line)
        )

    stage2 = ",\n".join("  {\n" + rows(block, 16) + "\n  }" for block in blocks)
    return f"""/* The simple lowercase mapping of fse_words@1, in two stages.

   {HEADER_NOTE}

   Code point cp below FSE_LOWER_LIMIT maps to cp + delta, with delta from block
   fse_lower_stage1[cp / {BLOCK}] of fse_lower_stage2 at cp % {BLOCK}; all others map to themselves. */
#ifndef FSE_NATIVE_UNICODE_H
#define FSE_NATIVE_UNICODE_H

#include <stdint.h>

#define FSE_UNICODE_VERSION "{UNICODE_VERSION}"
#define FSE_LOWER_LIMIT 0x{limit:X}u

static const uint8_t fse_lower_stage1[{len(stage1)}] = {{
{rows(stage1, 24)}
}};

static const int32_t fse_lower_stage2[{len(blocks)}][{BLOCK}] = {{
{stage2}
}};

static inline uint32_t fse_simple_lower(uint32_t cp) {{
    if (cp < 0x80u) return cp - 'A' < 26u ? cp | 0x20u : cp;
    if (cp >= FSE_LOWER_LIMIT) return cp;
    return (uint32_t)((int32_t)cp + fse_lower_stage2[fse_lower_stage1[cp / {BLOCK}]][cp % {BLOCK}]);
}}

#endif /* FSE_NATIVE_UNICODE_H */
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, required=True, help="UnicodeData.txt")
    parser.add_argument("--check", action="store_true", help="fail if the files are not current")
    args = parser.parse_args()
    table = read_simple_lowercase(args.ucd)
    check_against_python(table)
    outputs = {PYTHON_OUT: python_source(table), HEADER_OUT: header_source(table)}
    if args.check:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            raise SystemExit(f"not current: {', '.join(stale)}")
        print("the tables are current")
        return
    for path, text in outputs.items():
        path.write_text(text)
    print(f"{len(table)} mappings of Unicode {UNICODE_VERSION}")


if __name__ == "__main__":
    main()
