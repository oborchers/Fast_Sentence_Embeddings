"""Generate the grapheme data of unigram@1 from the Unicode Character Database.

The data are part of the tokenizer contract (ARCHITECTURE.md, "unigram@1"): the extended
grapheme clusters of UAX #29 in Unicode 17.0.0, the version of unicode-segmentation 1.13.3,
which Hugging Face tokenizers 0.23.3 uses for its Precompiled normalizer, and White_Space
of 17.0.0. Changing them needs a new tokenizer identifier. The script reads four UCD files
(each pinned by its sha256) and writes ``src/fse/_unicode_graphemes.py``, which is checked
in and never edited by hand. It also pins ``GraphemeBreakTest-17.0.0.txt``, the cases of
UAX #29 that ``tests/test_data`` holds. Download the files from
https://www.unicode.org/Public/17.0.0/ucd/ (the first two from ``auxiliary/`` and
``emoji/``) into one folder, named as in ``UCD`` below::

    uv run python tools/make_grapheme_tables.py --ucd <folder>
    uv run python tools/make_grapheme_tables.py --ucd <folder> --check
"""

from __future__ import annotations

import argparse
import hashlib
import re
from collections.abc import Iterable
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
PYTHON_OUT = ROOT / "src" / "fse" / "_unicode_graphemes.py"
VERSION = "17.0.0"
# The files, the Unicode version they come from, and their sha256.
UCD = {
    "GraphemeBreakProperty-17.0.0.txt": (
        "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89"
    ),
    "emoji-data-17.0.0.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    "DerivedCoreProperties-17.0.0.txt": (
        "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
    ),
    "PropList-17.0.0.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
}
# The test cases of UAX #29, checked in as tests/test_data/GraphemeBreakTest-17.0.0.txt.
TEST_FILE = "GraphemeBreakTest-17.0.0.txt"
TEST_SHA256 = "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec"
NOTE = (
    "Generated by tools/make_grapheme_tables.py from GraphemeBreakProperty.txt, "
    "emoji-data.txt, DerivedCoreProperties.txt and PropList.txt of Unicode 17.0.0; do not "
    "edit. Unicode data: Copyright (c) 1991-2025 Unicode, Inc., under the Unicode License "
    "v3 (see NOTICE)."
)
# The values of Grapheme_Cluster_Break other than Other, the default.
BREAK_VALUES = (
    "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
    "SpacingMark", "L", "V", "T", "LV", "LVT",
)  # fmt: skip
INCB_VALUES = ("Linker", "Consonant", "Extend")
_LINE = re.compile(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?")


def read(folder: Path, name: str, expected: str) -> str:
    data = (folder / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != expected:
        raise SystemExit(f"{name} has sha256 {digest}, not the pinned {expected}")
    return data.decode("utf-8")


def _file(folder: Path, name: str) -> str:
    return read(folder, name, UCD[name])


def _entries(text: str) -> Iterable[tuple[range, str, str | None]]:
    """(code points, property, value) of every data line."""
    for line in text.splitlines():
        match = _LINE.match(line.split("#")[0].strip())
        if match:
            first = int(match[1], 16)
            yield range(first, int(match[2] or match[1], 16) + 1), match[3], match[4]


def ranges(cps: Iterable[int]) -> list[tuple[int, int]]:
    """Sorted, disjoint, maximal ranges (first, last) of a set of code points."""
    out: list[list[int]] = []
    for cp in sorted(set(cps)):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [(a, b) for a, b in out]


def _breaks(text: str) -> dict[str, set[int]]:
    out: dict[str, set[int]] = {value: set() for value in BREAK_VALUES}
    seen: set[int] = set()
    for cps, value, _ in _entries(text):
        if value not in out:
            raise SystemExit(f"unknown Grapheme_Cluster_Break value {value}")
        if seen.intersection(cps):
            raise SystemExit(f"U+{cps[0]:04X} has two Grapheme_Cluster_Break values")
        seen.update(cps)
        out[value].update(cps)
    return out


def _property(text: str, name: str, value: str | None = None) -> set[int]:
    return {cp for cps, prop, val in _entries(text) if prop == name and val == value for cp in cps}


def check(data: SimpleNamespace) -> None:
    """The invariants the segmentation relies on."""
    breaks = {v: {cp for a, b in r for cp in range(a, b + 1)} for v, r in data.BREAKS.items()}
    every = set().union(*breaks.values())
    consonants = {cp for a, b in data.INCB["Consonant"] for cp in range(a, b + 1)}
    if consonants & every:
        raise SystemExit("an InCB=Consonant code point has a Grapheme_Cluster_Break value")
    linkers = {cp for a, b in data.INCB["Linker"] for cp in range(a, b + 1)}
    if not linkers <= breaks["Extend"]:
        raise SystemExit("an InCB=Linker code point is not Grapheme_Cluster_Break=Extend")
    if not linkers or not consonants or not data.EXTENDED_PICTOGRAPHIC:
        raise SystemExit("a property of the grapheme rules is empty")


def read_ucd(folder: Path) -> SimpleNamespace:
    """The data of the Python file, read from the UCD files, as range lists."""
    breaks = _breaks(_file(folder, "GraphemeBreakProperty-17.0.0.txt"))
    emoji = _file(folder, "emoji-data-17.0.0.txt")
    derived = _file(folder, "DerivedCoreProperties-17.0.0.txt")
    proplist = _file(folder, "PropList-17.0.0.txt")
    data = SimpleNamespace(
        BREAKS={value: ranges(cps) for value, cps in breaks.items()},
        EXTENDED_PICTOGRAPHIC=ranges(_property(emoji, "Extended_Pictographic")),
        INCB={value: ranges(_property(derived, "InCB", value)) for value in INCB_VALUES},
        WHITE_SPACE=ranges(_property(proplist, "White_Space")),
    )
    check(data)
    return data


def _range_text(spans: list[tuple[int, int]], indent: str = "") -> str:
    items = [f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in spans]
    lines, line = [], ""
    for item in items:
        if len(line) + len(item) + 1 > 84:
            lines.append(line)
            line = ""
        line += item + " "
    lines.append(line)
    if len(lines) == 1:
        return f'"{lines[0]}"'
    body = "\n".join(f'{indent}    "{chunk}"' for chunk in lines)
    return f"(\n{body}\n{indent})"


def python_source(data: SimpleNamespace) -> str:
    breaks = "\n".join(
        f'    "{value}": {_range_text(data.BREAKS[value], "    ")},' for value in BREAK_VALUES
    )
    incb = "\n".join(
        f'    "{value}": {_range_text(data.INCB[value], "    ")},' for value in INCB_VALUES
    )
    return f'''"""The grapheme data of unigram@1, for the reference fse._reference_unigram.

{NOTE}
"""

from bisect import bisect_right

VERSION = "{VERSION}"


class CodePoints:
    """A set of code points given as ranges "first-last" or single code points (hex),
    sorted and disjoint."""

    __slots__ = ("_starts", "ranges")

    def __init__(self, text: str):
        spans = [[int(x, 16) for x in item.split("-")] for item in text.split()]
        self.ranges = tuple((s[0], s[-1]) for s in spans)
        self._starts = tuple(first for first, _ in self.ranges)

    def __contains__(self, cp: object) -> bool:
        if not isinstance(cp, int):
            return False
        i = bisect_right(self._starts, cp) - 1
        return i >= 0 and cp <= self.ranges[i][1]


# The property Grapheme_Cluster_Break of {VERSION}, by value; every other code point is Other.
_BREAKS = {{
{breaks}
}}
# The property Extended_Pictographic of {VERSION} (emoji-data.txt).
_EXTENDED_PICTOGRAPHIC = {_range_text(data.EXTENDED_PICTOGRAPHIC)}
# The property InCB (Indic_Conjunct_Break) of {VERSION}, by value; every other code point is None.
_INCB = {{
{incb}
}}
# The property White_Space of {VERSION}.
_WHITE_SPACE = {_range_text(data.WHITE_SPACE)}

BREAKS = {{value: CodePoints(text) for value, text in _BREAKS.items()}}
EXTENDED_PICTOGRAPHIC = CodePoints(_EXTENDED_PICTOGRAPHIC)
INCB = {{value: CodePoints(text) for value, text in _INCB.items()}}
WHITE_SPACE = CodePoints(_WHITE_SPACE)
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, required=True, help="the folder of the UCD files")
    parser.add_argument("--check", action="store_true", help="fail if the file is not current")
    args = parser.parse_args()
    text = python_source(read_ucd(args.ucd))
    if args.check:
        if not PYTHON_OUT.exists() or PYTHON_OUT.read_text() != text:
            raise SystemExit(f"not current: {PYTHON_OUT}")
        print("the tables are current")
        return
    PYTHON_OUT.write_text(text)
    print(f"wrote {PYTHON_OUT}")


if __name__ == "__main__":
    main()
