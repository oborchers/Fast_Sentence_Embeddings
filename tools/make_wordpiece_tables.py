"""Generate the Unicode tables of wordpiece@1 from the Unicode Character Database.

The tables are part of the tokenizer contract (docs/architecture/tokenizers.md, "wordpiece@1"): their
Unicode versions are fixed (those of Hugging Face tokenizers 0.23.3: categories of 8.0.0,
normalization of 9.0.0, case and White_Space of 17.0.0), and changing them needs a new
tokenizer identifier. The script reads five UCD files (each pinned by its sha256) and writes
two files, which are checked in and never edited by hand:

- ``src/fse/_unicode_bert.py``: the data for the reference, as the UCD states it;
- ``src/fse/_native_unicode_bert.h``: the same composed per code point for the native
  tokenizer (steps 3.1 to 3.5 of one code point, with its combining class), in two stages.

The header is computed from the data of the Python file alone, so the tests regenerate it
from ``fse._unicode_bert`` and compare. Download the files from
https://www.unicode.org/Public/<version>/ucd/ into one folder, named as in ``UCD`` below::

    uv run python tools/make_wordpiece_tables.py --ucd <folder>
    uv run python tools/make_wordpiece_tables.py --ucd <folder> --check
"""

from __future__ import annotations

import argparse
import hashlib
import re
from collections.abc import Callable, Iterable
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
PYTHON_OUT = ROOT / "src" / "fse" / "_unicode_bert.py"
HEADER_OUT = ROOT / "src" / "fse" / "_native_unicode_bert.h"
VERSIONS = {"categories": "8.0.0", "normalization": "9.0.0", "case": "17.0.0"}
# The files, the Unicode version they come from, and their sha256.
UCD = {
    "UnicodeData-8.0.0.txt": "38b17e1118206489a7e0ab5d29d7932212d38838df7d3ec025ecb58e8798ec20",
    "UnicodeData-9.0.0.txt": "68dfc414d28257b9b5d6ddbb8b466c768c00ebdf6cbf7784364a9b6cad55ee8f",
    "UnicodeData-17.0.0.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "SpecialCasing-17.0.0.txt": "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
    "PropList-17.0.0.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
}
NOTE = (
    "Generated by tools/make_wordpiece_tables.py from UnicodeData.txt of Unicode 8.0.0, "
    "9.0.0 and 17.0.0, SpecialCasing.txt and PropList.txt of 17.0.0; do not edit. Unicode "
    "data: Copyright (c) 1991-2025 Unicode, Inc., under the Unicode License v3 (see NOTICE)."
)
# Private use (Co) as tokenizers' crate unicode_categories 0.1.1 tests it, by ranges.
PRIVATE_USE = ((0xE000, 0xF8FF), (0xF0000, 0xFFFFD), (0x100000, 0x10FFFD))
# Hangul syllables (the algorithm of the standard, section 3.12).
S_BASE, L_BASE, V_BASE, T_BASE, V_COUNT, T_COUNT, S_COUNT = (
    0xAC00, 0x1100, 0x1161, 0x11A7, 21, 28, 11172,
)  # fmt: skip
# The ranges of handle_chinese_chars (code in tokenizers, not Unicode data).
CJK = (
    (0x4E00, 0x9FFF), (0x3400, 0x4DBF), (0x20000, 0x2A6DF), (0x2A700, 0x2B73F),
    (0x2B740, 0x2B81F), (0x2B920, 0x2CEAF), (0xF900, 0xFAFF), (0x2F800, 0x2FA1F),
)  # fmt: skip
ASCII_PUNCTUATION = frozenset(map(ord, "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"))
MAX_CP = 0x10FFFF
BLOCK = 128
# The flags of an entry of the native table; the pool offset of its items is above them.
DROP, EXPAND, CJK_FLAG, HANGUL, SPACE, PUNCT = 0x01, 0x02, 0x04, 0x08, 0x10, 0x20
SHIFT = 8
# An item of the pool: (combining class << 24) | code point, or this for a removed mark of
# class 0, which ends a run of marks and writes nothing.
BARRIER = 0x00FFFFFF


def _read(folder: Path, name: str) -> str:
    data = (folder / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != UCD[name]:
        raise SystemExit(f"{name} has sha256 {digest}, not the pinned {UCD[name]}")
    return data.decode("utf-8")


def _unicode_data(text: str) -> Iterable[tuple[int, list[str]]]:
    """Every code point of UnicodeData.txt with its fields; ranges expanded."""
    first = None
    for line in text.splitlines():
        fields = line.split(";")
        if len(fields) != 15:
            raise SystemExit(f"malformed line: {line!r}")
        cp = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = cp
        elif fields[1].endswith(", Last>"):
            if first is None:
                raise SystemExit(f"a range ends without a start: {line!r}")
            yield from ((c, fields) for c in range(first, cp + 1))
            first = None
        else:
            yield cp, fields


def _categories(text: str) -> dict[int, str]:
    return {cp: fields[2] for cp, fields in _unicode_data(text)}


def _normalization(text: str) -> tuple[dict[int, tuple[int, ...]], dict[int, int]]:
    """The canonical decompositions (one level, Hangul aside) and nonzero classes."""
    decomposition, classes = {}, {}
    for cp, fields in _unicode_data(text):
        if fields[5] and not fields[5].startswith("<"):
            decomposition[cp] = tuple(int(x, 16) for x in fields[5].split())
        if int(fields[3]):
            classes[cp] = int(fields[3])
    return decomposition, classes


def _lowercase(unicode_data: str, special_casing: str) -> dict[int, tuple[int, ...]]:
    """The full lowercase mapping: field 13, replaced by the unconditional entries of
    SpecialCasing.txt; only where it is not the code point itself."""
    lower = {cp: (int(f[13], 16),) for cp, f in _unicode_data(unicode_data) if f[13]}
    for line in special_casing.splitlines():
        fields = [f.strip() for f in line.split("#")[0].split(";")]
        if len(fields) < 5:
            continue
        if fields[4]:  # a condition (language or context): Rust's to_lowercase ignores it
            continue
        lower[int(fields[0], 16)] = tuple(int(x, 16) for x in fields[1].split())
    return {cp: low for cp, low in lower.items() if low != (cp,)}


def _white_space(proplist: str) -> set[int]:
    out: set[int] = set()
    for line in proplist.splitlines():
        match = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*White_Space\b", line)
        if match:
            out.update(range(int(match[1], 16), int(match[2] or match[1], 16) + 1))
    return out


def ranges(cps: Iterable[int]) -> list[tuple[int, int]]:
    """Sorted, disjoint, maximal ranges (first, last) of a set of code points."""
    out: list[list[int]] = []
    for cp in sorted(set(cps)):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [(a, b) for a, b in out]


def read_ucd(folder: Path) -> SimpleNamespace:
    """The data of the Python file, read from the UCD files, as ``fse._unicode_bert``
    holds it (sets as range lists, mappings as dicts)."""
    cat8 = _categories(_read(folder, "UnicodeData-8.0.0.txt"))
    decomposition, classes = _normalization(_read(folder, "UnicodeData-9.0.0.txt"))
    other = {cp for cp, cat in cat8.items() if cat in ("Cc", "Cf", "Co")}
    private = {cp for cp, cat in cat8.items() if cat == "Co"}
    if ranges(private) != list(PRIVATE_USE):
        raise SystemExit("Co of Unicode 8.0.0 is not the ranges of unicode_categories")
    return SimpleNamespace(
        OTHER=ranges(other),
        NONSPACING_MARKS=ranges(cp for cp, cat in cat8.items() if cat == "Mn"),
        PUNCTUATION=ranges(cp for cp, cat in cat8.items() if cat.startswith("P")),
        WHITE_SPACE=ranges(_white_space(_read(folder, "PropList-17.0.0.txt"))),
        DECOMPOSITION=decomposition,
        COMBINING_CLASS=classes,
        LOWERCASE=_lowercase(
            _read(folder, "UnicodeData-17.0.0.txt"), _read(folder, "SpecialCasing-17.0.0.txt")
        ),
    )


# --- The Python file -------------------------------------------------------------------


def _chunks(items: list[str], quote: Callable[[str], str]) -> str:
    lines, line = [], ""
    for item in items:
        if len(line) + len(item) + 1 > 84:
            lines.append(line)
            line = ""
        line += item + " "
    lines.append(line)
    if len(lines) == 1:
        return quote(lines[0])
    return "(\n" + "\n".join(f"    {quote(chunk)}" for chunk in lines) + "\n)"


def _range_text(spans: list[tuple[int, int]]) -> str:
    items = [f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in spans]
    return _chunks(items, lambda chunk: f'"{chunk}"')


def _map_text(mapping: dict[int, tuple[int, ...]]) -> str:
    items = [f"{cp:x}:{','.join(f'{v:x}' for v in mapping[cp])}" for cp in sorted(mapping)]
    return _chunks(items, lambda chunk: f'"{chunk}"')


def python_source(data) -> str:
    def spans(value) -> str:
        return _range_text(list(getattr(value, "ranges", value)))

    classes = {cp: (c,) for cp, c in data.COMBINING_CLASS.items()}
    return f'''"""The Unicode data of wordpiece@1, for the reference fse._reference_wordpiece.

{NOTE}
"""

from bisect import bisect_right

CATEGORY_VERSION = "{VERSIONS["categories"]}"
NORMALIZATION_VERSION = "{VERSIONS["normalization"]}"
CASE_VERSION = "{VERSIONS["case"]}"


class CodePoints:
    """A set of code points given as ranges "first-last" or single code points (hex),
    sorted and disjoint."""

    __slots__ = ("_starts", "ranges")

    def __init__(self, text: str):
        spans = [[int(x, 16) for x in item.split("-")] for item in text.split()]
        self.ranges = tuple((s[0], s[-1]) for s in spans)
        self._starts = tuple(first for first, _ in self.ranges)

    def __contains__(self, cp: object) -> bool:
        if not isinstance(cp, int):
            return False
        i = bisect_right(self._starts, cp) - 1
        return i >= 0 and cp <= self.ranges[i][1]


def _mapping(text: str) -> dict[int, tuple[int, ...]]:
    """Entries "code point:value,value" (hex)."""
    out = {{}}
    for item in text.split():
        key, values = item.split(":")
        out[int(key, 16)] = tuple(int(v, 16) for v in values.split(","))
    return out


# Categories Cc, Cf and Co of {VERSIONS["categories"]} (clean_text removes them).
_OTHER = {spans(data.OTHER)}
# Category Mn of {VERSIONS["categories"]} (strip_accents removes them).
_NONSPACING_MARKS = {spans(data.NONSPACING_MARKS)}
# Categories Pc, Pd, Ps, Pe, Pi, Pf and Po of {VERSIONS["categories"]} (each is a word).
_PUNCTUATION = {spans(data.PUNCTUATION)}
# The property White_Space of {VERSIONS["case"]}.
_WHITE_SPACE = {spans(data.WHITE_SPACE)}
# The canonical decompositions of {VERSIONS["normalization"]}, one level (Hangul by the algorithm).
_DECOMPOSITION = {_map_text(data.DECOMPOSITION)}
# The nonzero canonical combining classes of {VERSIONS["normalization"]}.
_COMBINING_CLASS = {_map_text(classes)}
# The full lowercase mapping of {VERSIONS["case"]} where it is not the code point itself.
_LOWERCASE = {_map_text(data.LOWERCASE)}

OTHER = CodePoints(_OTHER)
NONSPACING_MARKS = CodePoints(_NONSPACING_MARKS)
PUNCTUATION = CodePoints(_PUNCTUATION)
WHITE_SPACE = CodePoints(_WHITE_SPACE)
DECOMPOSITION = _mapping(_DECOMPOSITION)
COMBINING_CLASS = {{cp: values[0] for cp, values in _mapping(_COMBINING_CLASS).items()}}
LOWERCASE = _mapping(_LOWERCASE)
'''


# --- The composed table of the native code ---------------------------------------------


class _Sets:
    """Fast membership of the range sets of ``data``."""

    def __init__(self, data):
        def expand(value) -> frozenset[int]:
            spans = getattr(value, "ranges", value)
            return frozenset(cp for a, b in spans for cp in range(a, b + 1))

        self.other = expand(data.OTHER)
        self.marks = expand(data.NONSPACING_MARKS)
        self.punct = expand(data.PUNCTUATION) | ASCII_PUNCTUATION
        self.space = expand(data.WHITE_SPACE) | {9, 10, 13}
        self.decomposition = data.DECOMPOSITION
        self.classes = data.COMBINING_CLASS
        self.lower = data.LOWERCASE


def is_hangul(cp: int) -> bool:
    return S_BASE <= cp < S_BASE + S_COUNT


def decompose(cp: int, sets: _Sets) -> list[int]:
    """The full canonical decomposition of one code point."""
    if is_hangul(cp):
        s = cp - S_BASE
        out = [L_BASE + s // (V_COUNT * T_COUNT), V_BASE + (s % (V_COUNT * T_COUNT)) // T_COUNT]
        return [*out, T_BASE + s % T_COUNT] if s % T_COUNT else out
    parts = sets.decomposition.get(cp)
    if parts is None:
        return [cp]
    return [x for part in parts for x in decompose(part, sets)]


def items(cp: int, sets: _Sets) -> list[int] | None:
    """What one code point of the input gives after steps 3.1, 3.3 to 3.5 (CJK aside): its
    items (class << 24 | code point, or BARRIER), or None if it is removed in step 3.1.

    A removed mark with a nonzero class leaves nothing (taking it out before ordering gives
    the same order of the rest); one of class 0 leaves a BARRIER. A multi-code-point
    lowercase gives items of the class of its code point."""
    if cp in (0, 0xFFFD) or (cp not in (9, 10, 13) and cp in sets.other):
        return None
    if cp in sets.space:
        return [0x20]
    out = []
    for part in decompose(cp, sets):
        cls = sets.classes.get(part, 0)
        if part in sets.marks:
            if cls == 0:
                out.append(BARRIER)
            continue
        out.extend((cls << 24) | low for low in sets.lower.get(part, (part,)))
    return out


def _utf8(cp: int) -> int:
    return 1 if cp < 0x80 else 2 if cp < 0x800 else 3 if cp < 0x10000 else 4


def _check(cp: int, found: list[int], cjk: bool) -> None:
    """The invariants the native code relies on."""
    out = sum(_utf8(i & 0xFFFFFF) for i in found if i != BARRIER) + (2 if cjk else 0)
    if out > 3 * _utf8(cp):
        raise SystemExit(f"U+{cp:04X} grows from {_utf8(cp)} to {out} bytes, more than 3 times")
    marks = [i for i in found if i >> 24]
    if cjk and (marks or BARRIER in found):
        raise SystemExit(f"U+{cp:04X} is CJK and gives marks")


def _entry(cp: int, sets: _Sets, cjk: bool, intern: Callable[[tuple[int, ...]], int]) -> int:
    """The native entry of one code point; ``intern`` gives the pool offset of items."""
    flags = (SPACE if cp in sets.space else 0) | (PUNCT if cp in sets.punct else 0)
    flags |= CJK_FLAG if cjk else 0
    if 0xD800 <= cp <= 0xDFFF:
        return flags  # never decoded
    found = items(cp, sets)
    if found is None:
        return flags | DROP
    _check(cp, found, cjk)
    if is_hangul(cp):
        return flags | HANGUL
    if found == [cp]:
        return flags
    if not found:
        return flags | DROP  # a mark that leaves nothing
    return flags | EXPAND | (intern(tuple(found)) << SHIFT)


def entries(data) -> tuple[list[int], list[int]]:
    """The native entry of every code point and the pool of items."""
    sets = _Sets(data)
    multi = sorted(cp for cp, low in sets.lower.items() if len(low) > 1)
    if multi != [0x0130]:
        raise SystemExit(f"multi-code-point lowercase beyond U+0130: {multi}")
    cjk_points = frozenset(cp for a, b in CJK for cp in range(a, b + 1))
    pool: list[int] = []
    known: dict[tuple[int, ...], int] = {}

    def intern(key: tuple[int, ...]) -> int:
        if key not in known:
            known[key] = len(pool)
            pool.extend((len(key), *key))
        return known[key]

    table = [_entry(cp, sets, cp in cjk_points, intern) for cp in range(MAX_CP + 1)]
    if len(pool) >= 1 << (32 - SHIFT):
        raise SystemExit("the pool does not fit the entries")
    return table, pool


def _rows(values: list[int], per_line: int, fmt: str = "{}") -> str:
    return ",\n".join(
        "    " + ", ".join(fmt.format(v) for v in values[i : i + per_line])
        for i in range(0, len(values), per_line)
    )


def header_source(data) -> str:
    table, pool = entries(data)
    blocks: list[tuple[int, ...]] = []
    index: dict[tuple[int, ...], int] = {}
    stage1 = []
    for start in range(0, len(table), BLOCK):
        block = tuple(table[start : start + BLOCK])
        stage1.append(index.setdefault(block, len(blocks)))
        if len(index) > len(blocks):
            blocks.append(block)
    stage2 = ",\n".join("  {\n" + _rows(list(b), 8, "0x{:x}") + "\n  }" for b in blocks)
    return f"""/* The composed normalization table of wordpiece@1, in two stages.

   {NOTE}

   fse_bert_entry(cp) holds the flags below and, above FSE_BERT_SHIFT, the offset of the
   items of cp in fse_bert_pool: a count, then the items (class << 24 | code point, or
   FSE_BERT_BARRIER for a removed mark of class 0). They are steps 3.1 and 3.3 to 3.5 of
   the code point alone (docs/architecture/tokenizers.md, "wordpiece@1"); CJK and Hangul are flags. The
   generator checks that a code point grows to at most 3 times its UTF-8 bytes and that
   only items of class 0 come from a multi-code-point lowercase. */
#ifndef FSE_NATIVE_UNICODE_BERT_H
#define FSE_NATIVE_UNICODE_BERT_H

#include <stdint.h>

#define FSE_BERT_DROP 0x{DROP:02x}u    /* removed: no output and no end of a run of marks */
#define FSE_BERT_EXPAND 0x{EXPAND:02x}u  /* gives the items in the pool */
#define FSE_BERT_CJK 0x{CJK_FLAG:02x}u     /* gets U+0020 before and after it */
#define FSE_BERT_HANGUL 0x{HANGUL:02x}u  /* a Hangul syllable, decomposed by the algorithm */
#define FSE_BERT_SPACE 0x{SPACE:02x}u   /* White_Space, as a code point of normalized text */
#define FSE_BERT_PUNCT 0x{PUNCT:02x}u   /* a word of its own, as a code point of normalized text */
#define FSE_BERT_SHIFT {SHIFT}
#define FSE_BERT_BARRIER 0x{BARRIER:06X}u

static const uint16_t fse_bert_stage1[{len(stage1)}] = {{
{_rows(stage1, 16)}
}};

static const uint32_t fse_bert_stage2[{len(blocks)}][{BLOCK}] = {{
{stage2}
}};

static const uint32_t fse_bert_pool[{len(pool)}] = {{
{_rows(pool, 8, "0x{:x}")}
}};

static inline uint32_t fse_bert_entry(uint32_t cp) {{
    return fse_bert_stage2[fse_bert_stage1[cp / {BLOCK}]][cp % {BLOCK}];
}}

#endif /* FSE_NATIVE_UNICODE_BERT_H */
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, required=True, help="the folder of the UCD files")
    parser.add_argument("--check", action="store_true", help="fail if the files are not current")
    args = parser.parse_args()
    data = read_ucd(args.ucd)
    outputs = {PYTHON_OUT: python_source(data), HEADER_OUT: header_source(data)}
    if args.check:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            raise SystemExit(f"not current: {', '.join(stale)}")
        print("the tables are current")
        return
    for path, text in outputs.items():
        path.write_text(text)
    print(f"{len(data.DECOMPOSITION)} decompositions, {len(data.LOWERCASE)} lowercase mappings")


if __name__ == "__main__":
    main()
